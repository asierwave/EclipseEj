package intento;

public class Camarote {

	private int numero;
	private String camarote;
	
	
	@Override
	public String toString() {
		return "Camarote [numero=" + numero + ", camarote=" + camarote + "]";
	}


	public Camarote(int numero, String camarote) {
		super();
		this.numero = numero;
		this.camarote = camarote;
	}
	
	
	
	
	
	
	
	
	
}
