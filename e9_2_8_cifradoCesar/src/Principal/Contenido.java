package Principal;

public class Contenido {

	
	private String letra;
	public int clave = 2;
	private String letraCodificada;
	
	
	public Contenido() {
		super();
	}
	
	
	
	public String getLetra() {
		return letra;
	}


	public void setLetra(String mensaje) {
		this.letra = letra;
	}


	public int getClave() {
		return clave;
	}


	public void setClave(int clave) {
		this.clave = clave;
	}


	public String getLetraCodificada() {
		return letraCodificada;
	}


	public void setMensajeFinal(String mensajeFinal) {
		this.letraCodificada = mensajeFinal;
	}



	
	
	
	
	
}
